"""Generates every Copy Box logo asset from one geometry definition.

Outputs (paths relative to the project root):
  android/app/src/main/res/drawable/ic_launcher_foreground.xml   108dp adaptive foreground
  android/app/src/main/res/drawable/ic_launcher_monochrome.xml   Android 13 themed icon
  android/app/src/main/res/drawable/ic_tile_clip.xml             Quick Settings tile glyph
  assets/logo/logo.svg                                           rounded tile (matches AppLogo)
  assets/logo/icon_1024.png                                      pink square + logo (store icon)
  assets/logo/icon_foreground.png                                transparent foreground

The same numbers are used by lib/ui/widgets/app_logo.dart (keep in sync).
Usage: python3 -I tool/generate_logo.py <project_root>
"""
import sys
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
PINK = '#FD79A8'
GRID = 108
CENTRE = 54
# Artwork = original design scaled to 78% around (54,54), so every corner is
# within 31 of the centre (inside the 33-radius circular safe zone of round masks).
RADIUS = 3.9
# (x, y, width, height, opacity): back, middle, front
CARDS_XYWH = [(43.08, 34.5, 34.32, 21.84, 0.4),
              (36.84, 43.08, 34.32, 21.84, 0.7),
              (30.6, 51.66, 34.32, 21.84, 1.0)]
CARDS = [(x, y, round(x + w, 2), round(y + h, 2), a) for x, y, w, h, a in CARDS_XYWH]
LINES = [((36.06, 58.68), (59.46, 58.68)), ((36.06, 64.14), (59.46, 64.14)), ((36.06, 68.82), (48.54, 68.82))]
STROKE = 2.0
SAFE_RADIUS = 31
LOGO_ZOOM = 1.25          # AppLogo / logo.svg
TILE_RADIUS = 0.24        # AppLogo tile corner radius, fraction of size


def fmt(v):
    return f'{round(v, 3):g}'


# Self-check: centred, and inside the safe circle.
import math
_xs = [c[0] for c in CARDS] + [c[2] for c in CARDS]
_ys = [c[1] for c in CARDS] + [c[3] for c in CARDS]
assert abs((min(_xs) + max(_xs)) / 2 - CENTRE) < 1e-6 and abs((min(_ys) + max(_ys)) / 2 - CENTRE) < 1e-6, 'artwork not centred'
assert max(math.hypot(x - CENTRE, y - CENTRE) for l, t, r, b, _ in CARDS for x in (l, r) for y in (t, b)) <= SAFE_RADIUS, 'corner outside safe radius'


def rrect_path(l, t, r, b, rad=RADIUS):
    """Rounded rectangle as an SVG/VectorDrawable path with quadratic corners."""
    return (f'M{fmt(l + rad)},{fmt(t)} H{fmt(r - rad)} Q{fmt(r)},{fmt(t)} {fmt(r)},{fmt(t + rad)} '
            f'V{fmt(b - rad)} Q{fmt(r)},{fmt(b)} {fmt(r - rad)},{fmt(b)} H{fmt(l + rad)} '
            f'Q{fmt(l)},{fmt(b)} {fmt(l)},{fmt(b - rad)} V{fmt(t + rad)} Q{fmt(l)},{fmt(t)} {fmt(l + rad)},{fmt(t)} Z')


def vector(width_dp, body, comment):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by tool/generate_logo.py - edit the geometry there, not here. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width_dp}dp"
    android:height="{width_dp}dp"
    android:viewportWidth="{GRID}"
    android:viewportHeight="{GRID}">
{body}</vector>
'''


def card_paths(color='#FFFFFFFF', indent='    '):
    out = ''
    for l, t, r, b, a in CARDS:
        alpha = '' if a == 1.0 else f'\n{indent}    android:fillAlpha="{fmt(a)}"'
        out += (f'{indent}<path\n{indent}    android:fillColor="{color}"{alpha}\n'
                f'{indent}    android:pathData="{rrect_path(l, t, r, b)}" />\n')
    return out


def line_paths(indent='    '):
    out = ''
    for (x1, y1), (x2, y2) in LINES:
        out += (f'{indent}<path\n{indent}    android:strokeColor="{PINK}"\n'
                f'{indent}    android:strokeWidth="{fmt(STROKE)}"\n'
                f'{indent}    android:strokeLineCap="round"\n'
                f'{indent}    android:pathData="M{fmt(x1)},{fmt(y1)} L{fmt(x2)},{fmt(y2)}" />\n')
    return out


def group(body, **attrs):
    a = ''.join(f'\n        android:{k}="{fmt(v)}"' for k, v in attrs.items())
    inner = ''.join('    ' + line + '\n' if line else '\n' for line in body.rstrip('\n').split('\n'))
    return f'    <group{a}>\n{inner}    </group>\n'


def write(rel, text, mode='w'):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    if mode == 'w':
        p.write_text(text)
    else:
        p.write_bytes(text)
    print('wrote', rel)


res = 'android/app/src/main/res/drawable/'
write(res + 'ic_launcher_foreground.xml', vector(108, card_paths() + line_paths(),
      'Copy Box adaptive-icon foreground: three stacked cards, white on #FD79A8.'))
write(res + 'ic_launcher_monochrome.xml', vector(108, card_paths(),
      'Android 13+ themed icon: the same cards in one colour, no lines.'))
write(res + 'ic_tile_clip.xml', vector(24, group(card_paths(), translateX=-27, translateY=-27, scaleX=1.5, scaleY=1.5),
      'Quick Settings tile glyph (system-tinted): the cards, no lines.'))
# The Android 12+ system splash uses a transparent icon (drawable/ic_splash_empty.xml), not the logo.

# ---- SVG (rounded tile, AppLogo zoom) ---------------------------------------
tile_r = GRID * TILE_RADIUS
svg_cards = ''.join(
    f'    <path d="{rrect_path(l, t, r, b)}" fill="#FFFFFF"{"" if a == 1 else f" fill-opacity=\"{fmt(a)}\""}/>\n'
    for l, t, r, b, a in CARDS)
svg_lines = ''.join(
    f'    <path d="M{fmt(x1)},{fmt(y1)} L{fmt(x2)},{fmt(y2)}" stroke="{PINK}" stroke-width="{fmt(STROKE)}" stroke-linecap="round"/>\n'
    for (x1, y1), (x2, y2) in LINES)
write('assets/logo/logo.svg', f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {GRID} {GRID}" width="512" height="512">
  <title>Copy Box</title>
  <rect width="{GRID}" height="{GRID}" rx="{fmt(round(tile_r, 2))}" fill="{PINK}"/>
  <g transform="translate(54 54) scale({LOGO_ZOOM}) translate(-54 -54)">
{svg_cards}{svg_lines}  </g>
</svg>
''')

# ---- PNGs (launcher geometry, 4x supersampled) -------------------------------
try:
    from PIL import Image, ImageDraw
except ImportError:
    print('Pillow not installed: skipped PNGs')
    sys.exit(0)


def render(size, background):
    ss = 4
    big = size * ss
    k = big / GRID
    img = Image.new('RGBA', (big, big), background or (0, 0, 0, 0))
    for l, t, r, b, a in CARDS:
        layer = Image.new('RGBA', img.size, (0, 0, 0, 0))
        ImageDraw.Draw(layer).rounded_rectangle([l * k, t * k, r * k, b * k], radius=RADIUS * k,
                                                fill=(255, 255, 255, round(255 * a)))
        img = Image.alpha_composite(img, layer)
    d = ImageDraw.Draw(img)
    pink = (0xFD, 0x79, 0xA8, 255)
    w = STROKE * k
    for (x1, y1), (x2, y2) in LINES:
        d.line([x1 * k, y1 * k, x2 * k, y2 * k], fill=pink, width=round(w))
        for x, y in ((x1, y1), (x2, y2)):   # round caps
            d.ellipse([x * k - w / 2, y * k - w / 2, x * k + w / 2, y * k + w / 2], fill=pink)
    return img.resize((size, size), Image.LANCZOS)


import io
for name, bg in (('icon_1024.png', (0xFD, 0x79, 0xA8, 255)), ('icon_foreground.png', None)):
    buf = io.BytesIO()
    render(1024, bg).save(buf, 'PNG', optimize=True)
    write('assets/logo/' + name, buf.getvalue(), mode='wb')
